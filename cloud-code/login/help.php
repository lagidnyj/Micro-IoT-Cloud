            <section id="alerts">
                <h2>Сповіщення Telegram</h2>
                <p>Правила сповіщень не редагуються в адмінці. Вони лежать у файлі налаштувань на сервері, тож змінює їх той, хто має доступ до сервера. Кожне правило описує: пристрій, параметр, умову (<code>&lt;=</code>, <code>&gt;=</code>, <code>==</code>, <code>!=</code>), порогове значення, чат Telegram і текст повідомлення.</p>

                <h3>Як надсилаються повідомлення</h3>
                <ul>
                    <li>Перше повідомлення приходить у момент, коли умова вперше спрацювала.</li>
                    <li>Поки умова тримається, нагадування приходять не частіше ніж раз на годину.</li>
                    <li>Коли значення повернулося в норму, наступне спрацювання знову сповістить одразу.</li>
                </ul>

                <div class="notice warn">
                    <b>На що не покладатися.</b>
                    <p>Якщо пристрій замовк і даних немає, правило просто пропускається, тому сповіщення «пристрій пропав» не буде. Стежте за статусами в адмінці.</p>
                    <p>Доставка не підтверджується: якщо Telegram був недоступний, хмара все одно вважає, що повідомлення надіслано. Для критичних аварій тримайте запасний канал.</p>
