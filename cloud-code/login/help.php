                <details>
                    <summary>Що саме має надсилати пристрій</summary>
                    <p>Для ручної перевірки endpoint є окрема сторінка «Тестер POST» у шапці адмінки. Вона не запам’ятовує адресу, ID чи токен; для запитів до іншого домену потрібен дозвіл CORS на сервері.</p>
                    <p>POST-запит із JSON-об’єктом стану на адресу хмари за HTTPS. Токен пристрою передається в заголовку <code>Authorization: Bearer ...</code>, а не в адресі. Кожен успішний запит повністю замінює попередній стан пристрою. Деталі формату знає той, хто пише прошивку.</p>
                </details>

                <details>
                    <summary>Чи зберігається історія значень?</summary>
                    <p>Ні. Хмара тримає лише останній стан кожного пристрою. Для графіків і архіву потрібне окреме сховище на стороні панелі.</p>
                </details>

